// The client side is what the client and the gateway exchange; the channel
// side is what the gateway and the model provider exchange. The call line
// stores the client side byte for byte (it is what the next request's history
// is built from); each channel attempt is stored as a delta against it, so a
// rewrite costs as many bytes as it changes (docs/traj_record/
// recording-v4-design-20261104.md, section 3.2).

// channelCaptureKey holds the *channelCapture of a recorded call on the gin
// context. Calls that are not recorded have none, so the relay hooks cost a
// context lookup and nothing else.
const channelCaptureKey = "traj_record_channel"

// channelBlobMin is the size above which a changed top-level value is stored
// as a blob, so a channel-injected system prompt is written once per day.
const channelBlobMin = 1 << 10

type channelCapture struct {
	mu       sync.Mutex
	maxResp  int
	attempts []*ChannelAttempt
}

// ChannelAttempt is one request sent to a channel. The relay gets it from
// ChannelRequest and reports the outcome with Response.
type ChannelAttempt struct {
	capture *channelCapture
	rec     channelAttempt
	body    []byte
	resp    bytes.Buffer
}

// channelAttempt is the stored form, one entry of callRecord.Channel. The raw
// bytes are reduced to a delta by the writer (diffChannel).
type channelAttempt struct {
	Attempt     int    `json:"attempt"`
	ChannelId   int    `json:"channel_id,omitempty"`
	ChannelType int    `json:"channel_type,omitempty"`
	Model       string `json:"model,omitempty"`
	// URL is scheme://host/path; the query is left out since some channels
	// put keys there.
	URL         string `json:"url,omitempty"`
	TsStart     int64  `json:"ts_start"`
	TsFirstByte int64  `json:"ts_first_byte,omitempty"`
	TsEnd       int64  `json:"ts_end,omitempty"`
	Error       string `json:"error,omitempty"`
	Status      int    `json:"status,omitempty"`

	Headers            map[string]string `json:"headers,omitempty"`
	HeadersDropped     []string          `json:"headers_dropped,omitempty"`
	RespHeaders        map[string]string `json:"resp_headers,omitempty"`
	RespHeadersDropped []string          `json:"resp_headers_dropped,omitempty"`

	ReqSize   int    `json:"req_size"`
	ReqSha256 string `json:"req_sha256"`
	// ReqCanonicalSha256 is the hash of the channel-side body as canonical
	// JSON, set with ReqSame or ReqDelta unless the bodies are equal byte for
	// byte (then ReqSha256 equals the call's req_sha256). It checks the
	// rebuilt body.
	ReqCanonicalSha256 string `json:"req_canonical_sha256,omitempty"`
	// Exactly one of ReqSame, ReqDelta or ReqRaw(B64) is set. ReqSame means
	// the two bodies are equal as canonical JSON (they usually differ in
	// bytes, since the gateway reserializes).
	ReqSame   bool          `json:"req_same,omitempty"`
	ReqDelta  *requestDelta `json:"req_delta,omitempty"`
	ReqRaw    *string       `json:"req_raw,omitempty"`
	ReqRawB64 []byte        `json:"req_raw_b64,omitempty"`

	RespContentType string `json:"resp_content_type,omitempty"`
	RespSize        int    `json:"resp_size"`
	RespTruncated   bool   `json:"resp_truncated,omitempty"`
	// RespComplete is the client-side summarizer run on the channel response:
	// whether the channel itself sent the terminal event.
	RespComplete bool `json:"resp_complete"`
	// Exactly one of RespSame, RespLines or Resp(B64) is set. For SSE,
	// RespSame and RespLines compare data lines only: event lines are
	// regenerated by the gateway, so channel-side event names are not kept.
	// RespLines lists the data lines that differ, by index among the data
	// lines, when both responses have the same number of them.
	RespSame  bool       `json:"resp_same,omitempty"`
	RespLines []respLine `json:"resp_lines,omitempty"`
	Resp      *string    `json:"resp,omitempty"`
	RespB64   []byte     `json:"resp_b64,omitempty"`
}

type respLine struct {
	Index int    `json:"i"`
	Data  string `json:"data"`
}

// requestDelta turns the client-side body into the channel-side one as
// canonical JSON (keys sorted, no insignificant whitespace, numbers as
// written). Set holds changed or added top-level values, Refs those stored as
// blobs, Del the removed keys, History the changed elements of the history
// array by index together with its new length.
type requestDelta struct {
	Set     map[string]json.RawMessage `json:"set,omitempty"`
	Refs    map[string]string          `json:"refs,omitempty"`
	Del     []string                   `json:"del,omitempty"`
	History *historyDelta              `json:"history,omitempty"`
}

type historyDelta struct {
	Len int                        `json:"len"`
	Set map[string]json.RawMessage `json:"set,omitempty"`
}

// ChannelRequest records req, about to be sent to a channel, and returns the
// attempt to report the response on. It returns nil (and Response is a no-op)
// when the call is not recorded. The body is read into memory and replaced by
// an equivalent reader.
//
// headerOverrideKeys names the headers the channel's header override wrote,
// from common.GetEffectiveHeaderOverride(info): it covers the runtime override
// that param_override's set_header/copy_header/move_header write, which the
// channel setting alone does not. Their values usually hold channel
// credentials, so only the names are kept, like upstream.header_override_keys.
// The exception is a header whose value is the client's own value for the
// same name: pass_headers (e.g. the built-in "claude cli trace" affinity rule)
// copies client headers into the override, and those are recorded on the
// client side under the same rules already.
func ChannelRequest(c *gin.Context, req *http.Request, attempt, channelId, channelType int, model string, headerOverrideKeys []string) *ChannelAttempt {
	if c == nil || req == nil {
		return nil
	}
	v, ok := c.Get(channelCaptureKey)
	if !ok {
		return nil
	}
	capture := v.(*channelCapture)
	a := &ChannelAttempt{capture: capture, rec: channelAttempt{
		Attempt: attempt, ChannelId: channelId, ChannelType: channelType, Model: model,
		TsStart: time.Now().UnixMilli(),
	}}
	if req.URL != nil {
		u := url.URL{Scheme: req.URL.Scheme, Host: req.URL.Host, Path: req.URL.Path}
		a.rec.URL = u.String()
	}
	var overridden []string
	for _, k := range headerOverrideKeys {
		v := req.Header.Values(k)
		if c.Request == nil || !slices.Equal(v, c.Request.Header.Values(k)) {
			overridden = append(overridden, k)
		}
	}
	a.rec.Headers, a.rec.HeadersDropped = filterHeaders(req.Header, overridden...)
	if req.Body != nil && req.Body != http.NoBody {
		body, err := io.ReadAll(req.Body)
		_ = req.Body.Close()
		a.body = body
		var rest io.Reader = bytes.NewReader(body)
		if err != nil {
			// Send what was read and then fail the same way the original
			// body would have.
			rest = io.MultiReader(rest, errReader{err})
			a.rec.Error = "read request body: " + err.Error()
		}
		req.Body = io.NopCloser(rest)
		if err == nil {
			req.GetBody = func() (io.ReadCloser, error) { return io.NopCloser(bytes.NewReader(body)), nil }
		}
	}
	capture.mu.Lock()
	capture.attempts = append(capture.attempts, a)
	capture.mu.Unlock()
	return a
}

type errReader struct{ err error }

func (e errReader) Read([]byte) (int, error) { return 0, e.err }

// Response records the channel's answer (or the transport error) and wraps
// resp.Body so that every byte the relay reads is captured.
func (a *ChannelAttempt) Response(resp *http.Response, err error) {
	if a == nil {
		return
	}
	a.capture.mu.Lock()
	defer a.capture.mu.Unlock()
	if err != nil {
		a.rec.Error = transportError(err)
		a.rec.TsEnd = time.Now().UnixMilli()
		return
	}
	if resp == nil {
		return
	}
	a.rec.Status = resp.StatusCode
	a.rec.RespContentType = resp.Header.Get("Content-Type")
	a.rec.RespHeaders, a.rec.RespHeadersDropped = filterHeaders(resp.Header)
	if resp.Body != nil {
		resp.Body = &channelBody{ReadCloser: resp.Body, a: a}
	}
}

// transportError drops the URL from *url.Error: it may carry a key in the query.
func transportError(err error) string {
	var ue *url.Error
	if errors.As(err, &ue) {
		return ue.Op + ": " + ue.Err.Error()
	}
	return err.Error()
}

// channelBody tees the channel response. The relay may read it from another
// goroutine (stream scanners), hence the capture lock.
type channelBody struct {
	io.ReadCloser
	a *ChannelAttempt
}

func (b *channelBody) Read(p []byte) (int, error) {
	n, err := b.ReadCloser.Read(p)
	a := b.a
	a.capture.mu.Lock()
	if n > 0 {
		if a.rec.TsFirstByte == 0 {
			a.rec.TsFirstByte = time.Now().UnixMilli()
		}
		a.rec.RespSize += n
		if room := a.capture.maxResp - a.resp.Len(); room < n {
			a.resp.Write(p[:max(room, 0)])
			a.rec.RespTruncated = true
		} else {
			a.resp.Write(p[:n])
		}
	}
	if err != nil && a.rec.TsEnd == 0 {
		a.rec.TsEnd = time.Now().UnixMilli()
		if !errors.Is(err, io.EOF) {
			a.rec.Error = "read response: " + err.Error()
		}
	}
	a.capture.mu.Unlock()
	return n, err
}

func (b *channelBody) Close() error {
	b.a.capture.mu.Lock()
	if b.a.rec.TsEnd == 0 {
		b.a.rec.TsEnd = time.Now().UnixMilli()
	}
	b.a.capture.mu.Unlock()
	return b.ReadCloser.Close()
}

// rawAttempt is an attempt snapshot handed to the writer.
type rawAttempt struct {
	rec  channelAttempt
	body []byte
	resp []byte
}

// snapshot copies the attempts when the call finishes. A body the relay never
// closed keeps whatever was read so far.
func (cc *channelCapture) snapshot() []rawAttempt {
	if cc == nil {
		return nil
	}
	cc.mu.Lock()
	defer cc.mu.Unlock()
	out := make([]rawAttempt, len(cc.attempts))
	for i, a := range cc.attempts {
		out[i] = rawAttempt{rec: a.rec, body: a.body, resp: bytes.Clone(a.resp.Bytes())}
	}
	return out
}

// diffChannel fills the stored form of one attempt. clientTop is the parsed
// client-side body (nil if it is not a JSON object); blob stores a large value
// and returns its reference.
func diffChannel(cl *client, a rawAttempt, clientBody []byte, clientTop map[string]json.RawMessage, clientResp []byte, clientContentType string, blob func(kind string, raw []byte) string) *channelAttempt {
	rec := a.rec
	rec.ReqSize = len(a.body)
	sum := sha256.Sum256(a.body)
	rec.ReqSha256 = hex.EncodeToString(sum[:])
	rec.ReqSame = bytes.Equal(a.body, clientBody)
	if !rec.ReqSame {
		var top map[string]json.RawMessage
		// A lone surrogate the channel still has cannot survive a delta: both
		// sides canonicalise to U+FFFD, so the record would claim the gateway
		// replaced it. Store the body as it is instead.
		if clientTop != nil && utf8.Valid(a.body) && countLoneSurrogates(a.body) == 0 &&
			common.Unmarshal(a.body, &top) == nil && top != nil {
			delta := diffRequest(cl.historyKey, clientTop, top, blob)
			if delta == nil {
				rec.ReqSame = true
			} else if size, _ := common.Marshal(delta); len(size) <= len(a.body)/2 {
				rec.ReqDelta = delta
			}
		}
		if !rec.ReqSame && rec.ReqDelta == nil {
			// Another protocol, or not JSON: a delta would not be smaller.
			if utf8.Valid(a.body) {
				raw := string(a.body)
				rec.ReqRaw = &raw
			} else {
				rec.ReqRawB64 = a.body
			}
		}
		if rec.ReqSame || rec.ReqDelta != nil {
			sum := sha256.Sum256(canonical(a.body))
			rec.ReqCanonicalSha256 = hex.EncodeToString(sum[:])
		}
	}

	var scratch callRecord
	scratch.RespContentType, scratch.RespTruncated = rec.RespContentType, rec.RespTruncated
	cl.summarize(&scratch, a.resp)
	rec.RespComplete = scratch.RespComplete
	switch {
	case bytes.Equal(a.resp, clientResp):
		rec.RespSame = true
	case isSSE(rec.RespContentType) && isSSE(clientContentType):
		rec.RespLines = diffDataLines(clientResp, a.resp)
		rec.RespSame = rec.RespLines != nil && len(rec.RespLines) == 0
		if rec.RespSame {
			rec.RespLines = nil
		}
	case !isSSE(rec.RespContentType) && !isSSE(clientContentType) && len(a.resp) > 0 &&
		comparableJSON(a.resp) && comparableJSON(clientResp) && canonicalEqual(a.resp, clientResp):
		rec.RespSame = true
	}
	if !rec.RespSame && rec.RespLines == nil && len(a.resp) > 0 {
		if utf8.Valid(a.resp) {
			raw := string(a.resp)
			rec.Resp = &raw
		} else {
			rec.RespB64 = a.resp
		}
	}
	return &rec
}

func isSSE(contentType string) bool {
	return strings.HasPrefix(contentType, "text/event-stream")
}

// diffDataLines compares the SSE data lines; event lines are regenerated by
// the gateway and ignored. It returns nil (store the whole response) unless
// both have the same number of data lines, at most half of them differ and
// every differing line is valid UTF-8 (a Go string would replace the rest).
// If none differ it returns an empty, non-nil slice.
func diffDataLines(client, channel []byte) []respLine {
	var cs, us [][]byte
	for p := range ssePayloads(client) {
		cs = append(cs, p)
	}
	for p := range ssePayloads(channel) {
		us = append(us, p)
	}
	if len(cs) != len(us) || len(us) == 0 {
		return nil
	}
	diff := []respLine{}
	for i := range us {
		if !bytes.Equal(cs[i], us[i]) {
			if !utf8.Valid(us[i]) {
				return nil
			}
			diff = append(diff, respLine{Index: i, Data: string(us[i])})
		}
	}
	if len(diff) > len(us)/2 {
		return nil
	}
	return diff
}

// diffRequest returns nil when the bodies are equal as canonical JSON.
func diffRequest(historyKey string, client, channel map[string]json.RawMessage, blob func(kind string, raw []byte) string) *requestDelta {
	d := &requestDelta{}
	for _, k := range slices.Sorted(maps.Keys(channel)) {
		v := channel[k]
		old, had := client[k]
		// The gateway reserializes, so the history rarely matches as bytes;
		// compare it element by element instead of decoding it whole first.
		if k == historyKey && had {
			if h, changed, ok := diffHistory(old, v); ok {
				if changed {
					d.History = h
				}
				continue
			}
		}
		if had && canonicalEqual(old, v) {
			continue
		}
		cv := canonical(v)
		if len(cv) >= channelBlobMin {
			if d.Refs == nil {
				d.Refs = map[string]string{}
			}
			d.Refs[k] = blob("channel:"+k, cv)
			continue
		}
		if d.Set == nil {
			d.Set = map[string]json.RawMessage{}
		}
		d.Set[k] = cv
	}
	for _, k := range slices.Sorted(maps.Keys(client)) {
		if _, ok := channel[k]; !ok {
			d.Del = append(d.Del, k)
		}
	}
	if d.Set == nil && d.Refs == nil && d.Del == nil && d.History == nil {
		return nil
	}
	return d
}

// diffHistory compares two history arrays element by element. ok is false
// if either is not an array.
func diffHistory(client, channel json.RawMessage) (h *historyDelta, changed, ok bool) {
	var cs, us []json.RawMessage
	if common.Unmarshal(client, &cs) != nil || common.Unmarshal(channel, &us) != nil {
		return nil, false, false
	}
	h = &historyDelta{Len: len(us)}
	for i, v := range us {
		if i < len(cs) && canonicalEqual(cs[i], v) {
			continue
		}
		if h.Set == nil {
			h.Set = map[string]json.RawMessage{}
		}
		h.Set[strconv.Itoa(i)] = canonical(v)
	}
	return h, h.Set != nil || len(us) != len(cs), true
}

// comparableJSON reports whether raw may be compared as canonical JSON
// without losing a real difference. Go's decoder turns invalid UTF-8 and lone
// surrogates into U+FFFD and ignores anything after the first value, so two
// bodies that differ only there would compare equal and the difference would
// never be stored (设计 3.8：网关的改动要由渠道侧记录反映).
//
// json.Valid requires the whole input to be exactly one value; a decoder's
// More() does not, since it returns false for a trailing } or ]. The UTF-8 and
// surrogate checks stay: json.Valid accepts invalid UTF-8 inside strings.
func comparableJSON(raw []byte) bool {
	return utf8.Valid(raw) && countLoneSurrogates(raw) == 0 && json.Valid(raw)
}

// canonical re-encodes JSON with sorted keys and no insignificant whitespace,
// keeping numbers as written. Invalid JSON is returned unchanged.
func canonical(raw []byte) json.RawMessage {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var v any
	if dec.Decode(&v) != nil {
		return raw
	}
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false)
	if enc.Encode(v) != nil {
		return raw
	}
	return bytes.TrimRight(out.Bytes(), "\n")
}

func canonicalEqual(a, b []byte) bool {
	return bytes.Equal(a, b) || bytes.Equal(canonical(a), canonical(b))
}

// countLoneSurrogates counts the \uD800–\uDFFF escapes in a JSON text that
// are not a high surrogate directly followed by a low one. Escapes only occur
// inside strings, so the text need not be parsed.
func countLoneSurrogates(raw []byte) int {
	n := 0
	pending := false // the previous escape was a high surrogate
	for i := 0; i < len(raw); i++ {
		if raw[i] != '\\' {
			if pending {
				n++
				pending = false
			}
			continue
		}
		if i+1 >= len(raw) {
			break
		}
		if raw[i+1] != 'u' || i+6 > len(raw) {
			if pending {
				n++
				pending = false
			}
			i++ // skip the escaped character, which may be a backslash
			continue
		}
		v, err := strconv.ParseUint(string(raw[i+2:i+6]), 16, 16)
		i += 5
		switch {
		case err != nil || v < 0xd800 || v > 0xdfff:
			if pending {
				n++
			}
			pending = false
		case v < 0xdc00:
			if pending {
				n++
			}
			pending = true
		case pending:
			pending = false
		default:
			n++
		}
	}
	if pending {
		n++
	}
	return n
}
