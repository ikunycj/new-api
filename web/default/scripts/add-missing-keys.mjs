  const file = path.join(LOCALES_DIR, `${locale}.json`)
  const json = JSON.parse(await fs.readFile(file, 'utf8'))
  Object.assign(
    json.translation,
    newKeys[locale],
    cacheStatsKeys[locale],
    loadTestDemoKeys[locale],
    routingStrategyKeys[locale],
    preservedLocaleValues[locale]
  )
